def compute_mu_predicted(patient_features, predicted_class, centroids):
    """
    patient_features: numpy array (6 values)
    predicted_class: 0 (Low), 1 (Medium), or 2 (High)
    centroids: saved FCM centroids
    """
    centroid = centroids[predicted_class]
    distance = np.linalg.norm(patient_features - centroid)
    mu = np.exp(-distance)
    return min(1.0, mu)

