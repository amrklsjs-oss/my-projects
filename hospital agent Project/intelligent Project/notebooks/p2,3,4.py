# CELL 4.10: Implement drift detection (Two signals)

def detect_arima_decline(forecast_values, n_weeks=4):
    """
    Detect if forecast shows consistent decline.

    Args:
        forecast_values: array of forecast values
        n_weeks: number of weeks to check

    Returns:
        drift_detected: boolean
    """
    if len(forecast_values) < n_weeks:
        return False

    recent = forecast_values[-n_weeks:]
    declines = [recent[i] < recent[i-1] for i in range(1, len(recent))]

    return all(declines)

def detect_centroid_drift(current_centroids, saved_centroids, threshold=0.3):
    """
    Detect if cluster centroids have shifted significantly.

    Args:
        current_centroids: array of current centroids (3, n_features)
        saved_centroids: array of saved centroids from training
        threshold: Euclidean distance threshold for drift

    Returns:
        drift_detected: boolean
        affected_cluster: int (0,1,2) or None
        distance: float
    """
    for cluster in range(3):
        distance = np.linalg.norm(current_centroids[cluster] - saved_centroids[cluster])
        if distance > threshold:
            return True, cluster, distance
    return False, None, None

