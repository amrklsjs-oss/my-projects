def calculate_risk_score(row):
    """
    Calculate risk score from 0 to 5 based on vital signs.
    This function expects UNSEALED values for heart_rate, systolic_bp, etc.
    """
    score = 0
    if row['heart_rate'] > 100:
        score += 1
    if row['systolic_bp'] > 140:
        score += 1
    if row['diastolic_bp'] > 90:
        score += 1
    if row['oxygen_saturation'] < 92:
        score += 1
    if row['temperature'] > 38:
        score += 1
    return score

def get_risk_category(score):
    """Convert risk score to category"""
