def compute_distance_to_centroid(row, centroids, feature_cols):
    """
    Calculate Euclidean distance from patient features to their assigned cluster's centroid.
    """
    risk_label = row['risk_label']

    # If risk_label is NaN, return NaN
    if pd.isna(risk_label):
        return np.nan

    centroid = centroids[int(risk_label)]
    features = row[feature_cols].values

    # Calculate Euclidean distance
    distance = np.linalg.norm(features - centroid)

    return distance

