# CELL 4.9: Compute ARIMA multiplier (1.2 / 1.0 / 0.7)

def compute_arima_multiplier(forecast, current_value):
    """
    Compute ARIMA multiplier based on forecasted trend.

    Rules:
    - Rising (Δ > +5%): 1.2 (amplify score)
    - Stable (|Δ| ≤ 5%): 1.0 (neutral)
    - Declining (Δ < -5%): 0.7 (dampen score)
    """
    avg_forecast = np.mean(forecast)
    percent_change = (avg_forecast - current_value) / current_value

    if percent_change > 0.05:
        return 1.2, 'rising', percent_change
    elif percent_change < -0.05:
        return 0.7, 'declining', percent_change
    else:
        return 1.0, 'stable', percent_change

